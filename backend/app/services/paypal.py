import httpx

from ..config import settings


def _base_url() -> str:
    if settings.paypal_mode == "live":
        return "https://api-m.paypal.com"
    return "https://api-m.sandbox.paypal.com"


def get_access_token() -> str:
    url = f"{_base_url()}/v1/oauth2/token"
    resp = httpx.post(
        url,
        auth=(settings.paypal_client_id, settings.paypal_client_secret),
        data={"grant_type": "client_credentials"},
        timeout=30,
    )
    resp.raise_for_status()
    return resp.json()["access_token"]


def create_paypal_invoice(invoice_data: dict) -> dict:
    token = get_access_token()
    headers = {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}
    body = {
        "detail": {
            "invoice_number": invoice_data["number"],
            "currency_code": invoice_data["currency"],
            "note": "Generated by PayPal AI prototype",
        },
        "invoicer": {"name": {"given_name": "Seller"}},
        "primary_recipients": [
            {
                "billing_info": {
                    "name": {"given_name": invoice_data["client_name"]},
                    "email_address": invoice_data["client_email"],
                }
            }
        ],
        "items": [
            {
                "name": item["description"],
                "quantity": str(item["quantity"]),
                "unit_amount": {
                    "currency_code": invoice_data["currency"],
                    "value": f"{item['unit_price']:.2f}",
                },
            }
            for item in invoice_data["items"]
        ],
    }
    url = f"{_base_url()}/v2/invoicing/invoices"
    resp = httpx.post(url, json=body, headers=headers, timeout=30)
    resp.raise_for_status()
    result = resp.json()
    invoice_id = result.get("id") or result.get("href", "").split("/")[-1]
    # send invoice to get payment link
    send_url = f"{_base_url()}/v2/invoicing/invoices/{invoice_id}/send"
    httpx.post(send_url, json={"send_to_recipient": True}, headers=headers, timeout=30)
    if settings.paypal_mode == "live":
        payment_link = f"https://www.paypal.com/invoice/p/{invoice_id}"
    else:
        payment_link = f"https://www.sandbox.paypal.com/invoice/p/{invoice_id}"
    return {"paypal_invoice_id": invoice_id, "payment_link": payment_link}